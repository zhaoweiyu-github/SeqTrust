from __future__ import annotations

import pickle
from pathlib import Path

import pandas as pd

from seqtrust.analysis.api import AnalysisMixin


class SeqTrust(AnalysisMixin):
    """Top-level DNA sequence evaluation manager.

    All records in ``df`` are processed as one single collection;
    there is no grouping concept.

    Core analysis functions are available directly on the evaluator:

    - ``st.add_seq2func_embedding(...)``
    - ``st.add_seq2func_prediction(...)``
    - ``st.add_seq2func_attribution(...)``
    - ``st.add_motif(...)``
    - ``st.add_seqlet(...)``
    - ``st.add_metrics(...)``

    Intermediate results that are not plain columns (attribution maps,
    motif scan tables, extracted seqlets) are stored in ``st.results``.
    """

    def __init__(
        self,
        df: pd.DataFrame,
        sequence_col: str = "Sequence",
        copy: bool = True,
    ):
        self.sequence_col = sequence_col
        self.df = df.copy() if copy else df
        self._check_columns()
        self.df[self.sequence_col] = self.df[self.sequence_col].astype(str).str.upper()
        self.history: list[str] = []
        self.feature_names: dict[str, list[str]] = {}
        self.results: dict = {}

    def _check_columns(self) -> None:
        if self.sequence_col not in self.df.columns:
            raise ValueError(
                f"Missing column: {self.sequence_col!r}. "
                f"Available columns: {list(self.df.columns)}"
            )

    def preview(self, n: int = 5) -> pd.DataFrame:
        return self.df.head(n)

    @property
    def info(self) -> dict:
        return {
            "n_rows": len(self.df),
            "sequence_col": self.sequence_col,
            "columns": list(self.df.columns),
            "history": self.history,
            "feature_names": self.feature_names,
        }

    def save(
        self,
        path: str | Path,
        protocol: int = pickle.HIGHEST_PROTOCOL,
    ) -> None:
        """
        Save the complete SeqTrust object.

        This preserves:
        - self.df
        - self.results
        - feature_names
        - history
        - all computed analysis results

        Parameters
        ----------
        path:
            Output pickle file.

        protocol:
            Pickle protocol version.
        """

        path = Path(path)

        with open(
            path,
            "wb",
        ) as f:

            pickle.dump(
                self,
                f,
                protocol=protocol,
            )

    @classmethod
    def load(
        cls,
        path: str | Path,
    ) -> "SeqTrust":
        """
        Load a saved SeqTrust object.

        Parameters
        ----------
        path:
            Pickle file generated by save().

        Returns
        -------
        SeqTrust
            Restored evaluator object.
        """

        path = Path(path)

        with open(
            path,
            "rb",
        ) as f:

            obj = pickle.load(f)

        if not isinstance(
            obj,
            cls,
        ):
            raise TypeError(
                f"Loaded object is {type(obj)}, "
                f"not {cls.__name__}"
            )

        return obj
